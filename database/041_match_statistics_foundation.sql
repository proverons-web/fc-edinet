-- Creates the durable data model for the v2.3 match-report branch:
-- report metadata, two team-stat rows per match, match events and an editor progress view.

create table if not exists public.match_reports (
  match_id bigint primary key
    references public.matches(id) on delete cascade,
  status text not null default 'draft'
    check (status in ('draft', 'complete')),
  referee text,
  attendance integer
    check (attendance is null or attendance between 0 and 200000),
  weather text,
  pitch_condition text,
  summary text,
  man_of_match_player_id uuid
    references public.players(id) on delete set null,
  completed_at timestamptz,
  completed_by uuid references auth.users(id) on delete set null,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.match_team_statistics (
  id bigint generated by default as identity primary key,
  match_id bigint not null
    references public.matches(id) on delete cascade,
  team_id bigint not null
    references public.teams(id) on delete restrict,
  side text not null
    check (side in ('home', 'away')),

  -- Nullable by design: NULL means "not entered yet", while 0 is a real value.
  possession_percent numeric(5,2)
    check (possession_percent is null or possession_percent between 0 and 100),
  shots smallint
    check (shots is null or shots between 0 and 100),
  shots_on_target smallint
    check (shots_on_target is null or shots_on_target between 0 and 100),
  corners smallint
    check (corners is null or corners between 0 and 60),
  fouls smallint
    check (fouls is null or fouls between 0 and 80),
  offsides smallint
    check (offsides is null or offsides between 0 and 40),
  yellow_cards smallint
    check (yellow_cards is null or yellow_cards between 0 and 20),
  red_cards smallint
    check (red_cards is null or red_cards between 0 and 10),
  passes_attempted smallint
    check (passes_attempted is null or passes_attempted between 0 and 1500),
  passes_completed smallint
    check (passes_completed is null or passes_completed between 0 and 1500),
  saves smallint
    check (saves is null or saves between 0 and 100),
  expected_goals numeric(5,2)
    check (expected_goals is null or expected_goals between 0 and 30),
  notes text,

  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint match_team_statistics_match_side_unique unique (match_id, side),
  constraint match_team_statistics_shots_target_lte_shots_check check (
    shots is null or shots_on_target is null or shots_on_target <= shots
  ),
  constraint match_team_statistics_passes_check check (
    passes_attempted is null or passes_completed is null or passes_completed <= passes_attempted
  )
);

create table if not exists public.match_events (
  id bigint generated by default as identity primary key,
  match_id bigint not null
    references public.matches(id) on delete cascade,
  team_id bigint
    references public.teams(id) on delete set null,
  player_id uuid
    references public.players(id) on delete set null,
  player_name text,
  related_player_id uuid
    references public.players(id) on delete set null,
  related_player_name text,
  event_type text not null
    check (event_type in (
      'goal', 'own_goal', 'penalty_goal', 'penalty_miss',
      'yellow_card', 'red_card', 'substitution', 'var',
      'injury', 'other'
    )),
  minute smallint not null default 0
    check (minute between 0 and 130),
  stoppage_minute smallint not null default 0
    check (stoppage_minute between 0 and 30),
  description text,
  sort_order integer not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists match_team_statistics_match_idx
