-- The side is the source of truth. The team id is always synchronized with
-- the current home/away teams of the match so a later match edit cannot leave
-- stale team-stat rows behind.
create or replace function public.sync_match_team_stat_context()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_home_team_id bigint;
  v_away_team_id bigint;
begin
  select home_team_id, away_team_id
  into v_home_team_id, v_away_team_id
  from public.matches
  where id = new.match_id;

  if v_home_team_id is null or v_away_team_id is null then
    raise exception 'Match % does not exist', new.match_id;
  end if;

  if new.side = 'home' then
    new.team_id := v_home_team_id;
  else
    new.team_id := v_away_team_id;
  end if;

  return new;
end;
$$;

drop trigger if exists match_team_statistics_sync_context on public.match_team_statistics;
create trigger match_team_statistics_sync_context
before insert or update of match_id, side, team_id on public.match_team_statistics
for each row execute function public.sync_match_team_stat_context();

-- Every match owns exactly two foundation rows: home and away. They are
-- created automatically for old matches and for every new match.
create or replace function public.ensure_match_team_stat_rows()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.match_team_statistics (match_id, team_id, side)
  values (new.id, new.home_team_id, 'home')
  on conflict (match_id, side) do update
    set team_id = excluded.team_id;

  insert into public.match_team_statistics (match_id, team_id, side)
  values (new.id, new.away_team_id, 'away')
  on conflict (match_id, side) do update
    set team_id = excluded.team_id;

  return new;
end;
$$;

drop trigger if exists matches_ensure_team_stat_rows on public.matches;
create trigger matches_ensure_team_stat_rows
after insert or update of home_team_id, away_team_id on public.matches
for each row execute function public.ensure_match_team_stat_rows();

insert into public.match_team_statistics (match_id, team_id, side)
select id, home_team_id, 'home'
from public.matches
on conflict (match_id, side) do update
set team_id = excluded.team_id;

insert into public.match_team_statistics (match_id, team_id, side)
select id, away_team_id, 'away'
from public.matches
on conflict (match_id, side) do update
set team_id = excluded.team_id;

