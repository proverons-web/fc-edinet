-- One compact progress source for the Match Center. This deliberately exposes
-- only workflow/count information, not detailed draft values.
drop view if exists public.match_center_progress;
create view public.match_center_progress
with (security_invoker = true)
as
select
  m.id as match_id,
  coalesce(mr.status, 'empty')::text as report_status,
  coalesce(mss.status, 'empty')::text as player_stats_status,
  count(distinct mts.id)::integer as team_rows,
  count(distinct mts.id) filter (
    where mts.possession_percent is not null
       or mts.shots is not null
       or mts.shots_on_target is not null
       or mts.corners is not null
       or mts.fouls is not null
       or mts.offsides is not null
       or mts.passes_attempted is not null
       or mts.expected_goals is not null
  )::integer as team_stats_filled,
  count(distinct me.id)::integer as events_count,
  (
    mr.referee is not null
    or mr.attendance is not null
    or mr.weather is not null
    or mr.pitch_condition is not null
    or mr.summary is not null
    or mr.man_of_match_player_id is not null
  ) as report_has_metadata
from public.matches m
left join public.match_reports mr on mr.match_id = m.id
left join public.match_statistics_status mss on mss.match_id = m.id
left join public.match_team_statistics mts on mts.match_id = m.id
left join public.match_events me on me.match_id = m.id
where public.is_editor_or_admin()
group by m.id, mr.status, mss.status, mr.referee, mr.attendance,
         mr.weather, mr.pitch_condition, mr.summary, mr.man_of_match_player_id;

grant select on table public.match_center_progress to authenticated;

notify pgrst, 'reload schema';
