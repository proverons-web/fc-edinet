create table if not exists public.seasons (
  id bigint generated by default as identity primary key,
  name text not null unique,
  slug text not null unique,
  starts_on date,
  ends_on date,
  is_current boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint seasons_dates_check check (
    starts_on is null or ends_on is null or starts_on <= ends_on
  )
);

-- Preserve seasons already typed into competitions.season.
insert into public.seasons (name, slug, is_current, is_active)
select distinct
  btrim(c.season),
  lower(regexp_replace(btrim(c.season), '[^a-zA-Z0-9]+', '-', 'g')) || '-' || substr(md5(btrim(c.season)), 1, 6),
  false,
  true
from public.competitions c
where c.season is not null and btrim(c.season) <> ''
on conflict do nothing;

-- Current project season. This is idempotent and only fills missing dates/current flag.
