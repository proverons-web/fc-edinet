create table if not exists public.player_match_stats (
  id bigint generated by default as identity primary key,
  match_id bigint not null
    references public.matches(id) on delete cascade,
  player_id uuid not null
    references public.players(id) on delete cascade,
  competition_id bigint
    references public.competitions(id) on delete set null,
  season_id bigint
    references public.seasons(id) on delete set null,
  team_id bigint
    references public.teams(id) on delete set null,

  appearance text not null default 'starter'
    check (appearance in ('starter', 'substitute')),
  position text
    check (
      position is null
      or position in ('goalkeeper', 'defender', 'midfielder', 'forward')
    ),
  is_captain boolean not null default false,
  minutes_played smallint not null default 0
    check (minutes_played between 0 and 130),

  goals smallint not null default 0 check (goals between 0 and 20),
  assists smallint not null default 0 check (assists between 0 and 20),
  own_goals smallint not null default 0 check (own_goals between 0 and 10),
  penalties_scored smallint not null default 0 check (penalties_scored between 0 and 20),
  penalties_missed smallint not null default 0 check (penalties_missed between 0 and 20),
  yellow_cards smallint not null default 0 check (yellow_cards between 0 and 2),
  red_cards smallint not null default 0 check (red_cards between 0 and 1),

  -- Goalkeeper-ready fields are stored from the start so v2.2.x will not need
  -- a destructive schema redesign when goalkeeper statistics are enabled.
  goals_conceded smallint not null default 0 check (goals_conceded between 0 and 30),
  saves smallint not null default 0 check (saves between 0 and 50),
  clean_sheet boolean not null default false,

  notes text,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint player_match_stats_match_player_unique unique (match_id, player_id)
);

create index if not exists player_match_stats_player_season_idx
  on public.player_match_stats (player_id, season_id, competition_id);
create index if not exists player_match_stats_match_idx
  on public.player_match_stats (match_id);
create index if not exists player_match_stats_season_competition_idx
  on public.player_match_stats (season_id, competition_id);

create table if not exists public.match_statistics_status (
  match_id bigint primary key
    references public.matches(id) on delete cascade,
  status text not null default 'draft'
    check (status in ('draft', 'complete')),
  completed_at timestamptz,
  completed_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Keep season / competition / club-team context in every row consistent with the match.
create or replace function public.sync_player_match_stat_context()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_competition_id bigint;
  v_season_id bigint;
  v_home_team_id bigint;
  v_away_team_id bigint;
  v_home_is_club boolean;
  v_away_is_club boolean;
begin
  select
    m.competition_id,
    c.season_id,
    m.home_team_id,
    m.away_team_id,
    coalesce(ht.is_club, false),
    coalesce(at.is_club, false)
  into
    v_competition_id,
    v_season_id,
    v_home_team_id,
    v_away_team_id,
    v_home_is_club,
    v_away_is_club
  from public.matches m
  left join public.competitions c on c.id = m.competition_id
  left join public.teams ht on ht.id = m.home_team_id
  left join public.teams at on at.id = m.away_team_id
  where m.id = new.match_id;

  if v_home_team_id is null then
    raise exception 'Match % does not exist', new.match_id;
  end if;

  new.competition_id := v_competition_id;
  new.season_id := v_season_id;

  if v_home_is_club then
    new.team_id := v_home_team_id;
  elsif v_away_is_club then
    new.team_id := v_away_team_id;
  elsif new.team_id is null then
    new.team_id := v_home_team_id;
  end if;

  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists player_match_stats_sync_context on public.player_match_stats;
create trigger player_match_stats_sync_context
before insert or update of match_id on public.player_match_stats
for each row execute function public.sync_player_match_stat_context();

-- If a match is moved to another tournament, refresh already entered stats context.
create or replace function public.refresh_match_stats_context()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.competition_id is distinct from old.competition_id
     or new.home_team_id is distinct from old.home_team_id
     or new.away_team_id is distinct from old.away_team_id then
    update public.player_match_stats
      set match_id = new.id
      where match_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists matches_refresh_player_stats_context on public.matches;
create trigger matches_refresh_player_stats_context
after update of competition_id, home_team_id, away_team_id on public.matches
for each row execute function public.refresh_match_stats_context();

