-- FC Edinet v2.13.0 — privacy-friendly visitor analytics
-- Unique visitor = anonymous browser identifier hashed by the application.
-- No IP addresses are stored.

create table if not exists public.site_visitors (
  visitor_hash text primary key,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  pageviews bigint not null default 0,
  last_path text,
  first_referrer text,
  last_referrer text,
  constraint site_visitors_hash_check check (visitor_hash ~ '^[0-9a-f]{64}$')
);

create index if not exists site_visitors_last_seen_idx on public.site_visitors (last_seen desc);
create index if not exists site_visitors_first_seen_idx on public.site_visitors (first_seen desc);

create table if not exists public.site_pageviews (
  id bigint generated by default as identity primary key,
  visitor_hash text not null references public.site_visitors(visitor_hash) on delete cascade,
  path text not null,
  referrer text,
  visited_at timestamptz not null default now()
);

create index if not exists site_pageviews_visited_at_idx on public.site_pageviews (visited_at desc);
create index if not exists site_pageviews_path_idx on public.site_pageviews (path);
create index if not exists site_pageviews_visitor_idx on public.site_pageviews (visitor_hash, visited_at desc);

alter table public.site_visitors enable row level security;
alter table public.site_pageviews enable row level security;

-- Keep raw analytics tables private. Public/admin access goes through narrow RPCs.
revoke all on table public.site_visitors from public, anon, authenticated;
revoke all on table public.site_pageviews from public, anon, authenticated;
revoke all on sequence public.site_pageviews_id_seq from public, anon, authenticated;

create or replace function public.record_site_visit(
  p_visitor_hash text,
  p_path text,
  p_referrer text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_path text;
  v_referrer text;
begin
  if p_visitor_hash is null or p_visitor_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'Invalid visitor identifier.' using errcode = '22023';
  end if;

  v_path := left(coalesce(nullif(trim(p_path), ''), '/'), 500);
  if left(v_path, 1) <> '/' then
    v_path := '/' || v_path;
  end if;
  v_referrer := nullif(left(trim(coalesce(p_referrer, '')), 500), '');

  insert into public.site_visitors (
    visitor_hash, first_seen, last_seen, pageviews, last_path, first_referrer, last_referrer
  ) values (
    p_visitor_hash, now(), now(), 1, v_path, v_referrer, v_referrer
  )
  on conflict (visitor_hash) do update
    set last_seen = excluded.last_seen,
        pageviews = public.site_visitors.pageviews + 1,
        last_path = excluded.last_path,
        last_referrer = excluded.last_referrer;

  insert into public.site_pageviews (visitor_hash, path, referrer, visited_at)
  values (p_visitor_hash, v_path, v_referrer, now());
end;
$$;

create or replace function public.get_public_visit_counts()
returns table (
  unique_24h bigint,
  unique_7d bigint,
  unique_30d bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    count(*) filter (where last_seen >= now() - interval '24 hours')::bigint,
    count(*) filter (where last_seen >= now() - interval '7 days')::bigint,
    count(*) filter (where last_seen >= now() - interval '30 days')::bigint
  from public.site_visitors;
$$;

create or replace function public.admin_site_analytics(p_days integer default 30)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_days integer := greatest(1, least(coalesce(p_days, 30), 365));
  v_start timestamptz := now() - make_interval(days => greatest(1, least(coalesce(p_days, 30), 365)));
  v_result jsonb;
begin
  if auth.uid() is null
    or coalesce(public.current_user_role() in ('editor'::public.user_role, 'admin'::public.user_role), false) is not true
  then
    raise exception 'Недостаточно прав для просмотра статистики сайта.' using errcode = '42501';
  end if;

  select jsonb_build_object(
    'period_days', v_days,
    'summary', jsonb_build_object(
      'unique_24h', (select count(*) from public.site_visitors where last_seen >= now() - interval '24 hours'),
      'unique_7d', (select count(*) from public.site_visitors where last_seen >= now() - interval '7 days'),
      'unique_30d', (select count(*) from public.site_visitors where last_seen >= now() - interval '30 days'),
      'unique_total', (select count(*) from public.site_visitors),
      'pageviews_24h', (select count(*) from public.site_pageviews where visited_at >= now() - interval '24 hours'),
      'pageviews_7d', (select count(*) from public.site_pageviews where visited_at >= now() - interval '7 days'),
      'pageviews_30d', (select count(*) from public.site_pageviews where visited_at >= now() - interval '30 days'),
      'pageviews_total', (select count(*) from public.site_pageviews),
      'period_unique', (select count(*) from public.site_visitors where last_seen >= v_start),
      'period_pageviews', (select count(*) from public.site_pageviews where visited_at >= v_start),
      'period_new', (select count(*) from public.site_visitors where first_seen >= v_start),
      'period_returning', (select count(*) from public.site_visitors where last_seen >= v_start and first_seen < v_start)
    ),
    'daily', coalesce((
      select jsonb_agg(jsonb_build_object(
        'date', d.day::text,
        'unique', coalesce(s.unique_visitors, 0),
        'pageviews', coalesce(s.pageviews, 0)
      ) order by d.day)
      from generate_series(
        (current_date - (v_days - 1))::timestamp,
        current_date::timestamp,
        interval '1 day'
      ) as d(day)
      left join (
        select
          (visited_at at time zone 'Europe/Chisinau')::date as day,
          count(distinct visitor_hash)::bigint as unique_visitors,
          count(*)::bigint as pageviews
        from public.site_pageviews
        where visited_at >= v_start
        group by 1
      ) s on s.day = d.day::date
    ), '[]'::jsonb),
    'top_pages', coalesce((
      select jsonb_agg(to_jsonb(x) order by x.pageviews desc, x.unique_visitors desc)
      from (
        select path, count(*)::bigint as pageviews, count(distinct visitor_hash)::bigint as unique_visitors
        from public.site_pageviews
        where visited_at >= v_start
        group by path
        order by pageviews desc, unique_visitors desc
        limit 20
      ) x
    ), '[]'::jsonb),
    'referrers', coalesce((
      select jsonb_agg(to_jsonb(x) order by x.pageviews desc)
      from (
        select coalesce(nullif(referrer, ''), 'Прямые заходы') as source,
               count(*)::bigint as pageviews,
               count(distinct visitor_hash)::bigint as unique_visitors
        from public.site_pageviews
        where visited_at >= v_start
        group by 1
        order by pageviews desc
        limit 15
      ) x
    ), '[]'::jsonb),
    'recent', coalesce((
      select jsonb_agg(to_jsonb(x) order by x.last_seen desc)
      from (
        select left(visitor_hash, 8) as visitor,
               first_seen,
               last_seen,
               pageviews,
               last_path,
               coalesce(last_referrer, 'Прямой заход') as referrer
        from public.site_visitors
        order by last_seen desc
        limit 30
      ) x
    ), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;

