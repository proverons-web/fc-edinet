create table if not exists public.club_profile (
  id smallint primary key default 1 check (id = 1),
  club_name text not null default 'FC Edineț',
  city text not null default 'Edineț',
  founded_year integer check (
    founded_year is null or founded_year between 1900 and 2100
  ),
  club_colors text,
  motto text,

  about_text text,
  history_text text,

  email text,
  phone text,
  address text,

  stadium_name text,
  stadium_capacity integer check (
    stadium_capacity is null or stadium_capacity >= 0
  ),
  stadium_address text,
  stadium_description text,

  hero_image_url text,
  stadium_image_url text,

  updated_at timestamptz not null default now()
);

