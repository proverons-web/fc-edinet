alter table public.site_global_designs enable row level security;
alter table public.site_global_design_drafts enable row level security;
alter table public.site_global_design_versions enable row level security;

-- Published config is public.
drop policy if exists "Public can read global designs" on public.site_global_designs;
create policy "Public can read global designs" on public.site_global_designs for select to anon, authenticated using (true);
drop policy if exists "Editors can insert global designs" on public.site_global_designs;
create policy "Editors can insert global designs" on public.site_global_designs for insert to authenticated with check (public.is_editor_or_admin());
drop policy if exists "Editors can update global designs" on public.site_global_designs;
create policy "Editors can update global designs" on public.site_global_designs for update to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

-- Drafts never have a public read policy.
drop policy if exists "Editors can read global drafts" on public.site_global_design_drafts;
create policy "Editors can read global drafts" on public.site_global_design_drafts for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors can insert global drafts" on public.site_global_design_drafts;
create policy "Editors can insert global drafts" on public.site_global_design_drafts for insert to authenticated with check (public.is_editor_or_admin());
drop policy if exists "Editors can update global drafts" on public.site_global_design_drafts;
create policy "Editors can update global drafts" on public.site_global_design_drafts for update to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());
drop policy if exists "Editors can delete global drafts" on public.site_global_design_drafts;
create policy "Editors can delete global drafts" on public.site_global_design_drafts for delete to authenticated using (public.is_editor_or_admin());

-- Version history is staff-only.
drop policy if exists "Editors can read global versions" on public.site_global_design_versions;
create policy "Editors can read global versions" on public.site_global_design_versions for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors can insert global versions" on public.site_global_design_versions;
create policy "Editors can insert global versions" on public.site_global_design_versions for insert to authenticated with check (public.is_editor_or_admin());
drop policy if exists "Admins can delete global versions" on public.site_global_design_versions;
create policy "Admins can delete global versions" on public.site_global_design_versions for delete to authenticated using (public.current_user_role() = 'admin');

grant select on public.site_global_designs to anon, authenticated;
grant insert, update on public.site_global_designs to authenticated;
grant select, insert, update, delete on public.site_global_design_drafts to authenticated;
grant select, insert, delete on public.site_global_design_versions to authenticated;

drop trigger if exists set_site_global_designs_updated_at on public.site_global_designs;
create trigger set_site_global_designs_updated_at before update on public.site_global_designs for each row execute function public.set_updated_at();
drop trigger if exists set_site_global_drafts_updated_at on public.site_global_design_drafts;
create trigger set_site_global_drafts_updated_at before update on public.site_global_design_drafts for each row execute function public.set_updated_at();

drop trigger if exists audit_log_site_global_designs on public.site_global_designs;
create trigger audit_log_site_global_designs after insert or update or delete on public.site_global_designs for each row execute function public.write_audit_log();
