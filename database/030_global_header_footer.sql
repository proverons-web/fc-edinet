create table if not exists public.site_global_designs (
  component_key text primary key check (component_key in ('header','footer')),
  config jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.site_global_design_drafts (
  component_key text primary key check (component_key in ('header','footer')),
  config jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.site_global_design_versions (
  id bigint generated by default as identity primary key,
  component_key text not null check (component_key in ('header','footer')),
  label text,
  snapshot jsonb not null,
  published_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists site_global_design_versions_component_created_idx on public.site_global_design_versions(component_key, created_at desc);
create index if not exists site_global_designs_updated_by_idx on public.site_global_designs(updated_by);
create index if not exists site_global_drafts_updated_by_idx on public.site_global_design_drafts(updated_by);
create index if not exists site_global_versions_published_by_idx on public.site_global_design_versions(published_by);

