-- Public media bucket.
insert into storage.buckets (
  id,
  name,
  public,
  file_size_limit,
  allowed_mime_types
)
values (
  'media',
  'media',
  true,
  12582912,
  array['image/jpeg','image/png','image/webp']
)
on conflict (id) do update
set
  name = excluded.name,
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Public can view media files" on storage.objects;
create policy "Public can view media files"
on storage.objects
for select
to public
using (bucket_id = 'media');

drop policy if exists "Editors upload media files" on storage.objects;
create policy "Editors upload media files"
on storage.objects
for insert
to authenticated
with check (
  bucket_id = 'media'
  and public.is_editor_or_admin()
  and (storage.foldername(name))[1] = (select auth.uid())::text
  and lower(storage.extension(name)) in ('jpg','jpeg','png','webp')
);

drop policy if exists "Editors delete media files" on storage.objects;
create policy "Editors delete media files"
on storage.objects
for delete
to authenticated
using (
  bucket_id = 'media'
  and public.is_editor_or_admin()
);
