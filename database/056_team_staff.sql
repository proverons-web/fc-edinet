create table if not exists public.team_staff (
  id bigint generated by default as identity primary key,
  first_name text not null,
  last_name text not null,
  role_key text not null,
  role_title text not null,
  role_title_ro text,
  category text not null default 'coaching' check (category in ('coaching','medical','operations')),
  bio text,
  bio_ro text,
  photo_url text,
  joined_year integer,
  left_year integer,
  display_order integer not null default 100,
  is_active boolean not null default true,
  is_placeholder boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists team_staff_active_order_idx on public.team_staff (is_active,category,display_order,id);
drop trigger if exists team_staff_set_updated_at on public.team_staff;
create trigger team_staff_set_updated_at before update on public.team_staff for each row execute function public.set_generic_updated_at();
alter table public.team_staff enable row level security;
grant select on table public.team_staff to anon, authenticated;
grant insert, update, delete on table public.team_staff to authenticated;
grant usage, select on sequence public.team_staff_id_seq to authenticated;
drop policy if exists "Public can read active team staff" on public.team_staff;
create policy "Public can read active team staff" on public.team_staff for select to public using (is_active=true);
drop policy if exists "Editors read all team staff" on public.team_staff;
create policy "Editors read all team staff" on public.team_staff for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors manage team staff" on public.team_staff;
create policy "Editors manage team staff" on public.team_staff for all to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());
drop trigger if exists audit_log_team_staff on public.team_staff;
create trigger audit_log_team_staff after insert or update or delete on public.team_staff for each row execute function public.write_audit_log();
