-- FC Edineț v2.30.7 — independently editable, sourced club history timeline.
-- Run once AFTER 057_club_archive_hall_of_fame.sql and 034_player_statistics_foundation.sql.
-- Does not overwrite existing history text, achievements, seasons or Hall of Fame.
-- No synthetic events are inserted. Historical claims must be entered by an editor.

create table if not exists public.club_history_events (
  id bigint generated by default as identity primary key,
  event_year integer not null check (event_year between 1850 and 2100),
  event_month integer check (event_month between 1 and 12),
  event_kind text not null default 'milestone' check (event_kind in ('milestone','achievement','people','squad','stadium')),
  title text not null check (length(btrim(title)) between 1 and 180),
  title_ro text check (title_ro is null or length(title_ro) <= 180),
  description text check (description is null or length(description) <= 6000),
  description_ro text check (description_ro is null or length(description_ro) <= 6000),
  image_url text,
  source_url text check (source_url is null or source_url ~ '^https://[^[:space:]]+$'),
  season_id bigint references public.seasons(id) on delete set null,
  hall_entry_id bigint references public.club_hall_of_fame(id) on delete set null,
  display_order integer not null default 100 check (display_order between 0 and 100000),
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists club_history_events_public_idx
  on public.club_history_events (is_published, event_year desc, event_month desc, display_order, id);
create index if not exists club_history_events_season_idx
  on public.club_history_events (season_id, is_published, event_year desc);
create index if not exists club_history_events_hall_idx
  on public.club_history_events (hall_entry_id, is_published, event_year desc);

alter table public.club_history_events enable row level security;
grant select on public.club_history_events to anon, authenticated;
grant insert, update, delete on public.club_history_events to authenticated;
grant usage, select on sequence public.club_history_events_id_seq to authenticated;

drop policy if exists "Public read published history events" on public.club_history_events;
create policy "Public read published history events" on public.club_history_events
  for select to anon, authenticated using (is_published = true);
drop policy if exists "Editors read unpublished history events" on public.club_history_events;
create policy "Editors read unpublished history events" on public.club_history_events
  for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors create history events" on public.club_history_events;
create policy "Editors create history events" on public.club_history_events
  for insert to authenticated with check (public.is_editor_or_admin());
drop policy if exists "Editors update history events" on public.club_history_events;
create policy "Editors update history events" on public.club_history_events
  for update to authenticated
  using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());
drop policy if exists "Editors delete history events" on public.club_history_events;
create policy "Editors delete history events" on public.club_history_events
  for delete to authenticated using (public.is_editor_or_admin());

drop trigger if exists club_history_events_set_updated_at on public.club_history_events;
create trigger club_history_events_set_updated_at before update on public.club_history_events
  for each row execute function public.set_generic_updated_at();
drop trigger if exists audit_log_club_history_events on public.club_history_events;
create trigger audit_log_club_history_events after insert or update or delete on public.club_history_events
  for each row execute function public.write_audit_log();

notify pgrst, 'reload schema';
