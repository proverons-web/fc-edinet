create table if not exists public.site_custom_pages (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9][a-z0-9-]{0,79}$'),
  title_ru text not null,
  title_ro text not null default '',
  intro_ru text not null default '',
  intro_ro text not null default '',
  body_ru text not null default '',
  body_ro text not null default '',
  hero_image_url text,
  status text not null default 'draft' check (status in ('draft','published')),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz
);

create index if not exists site_custom_pages_status_idx on public.site_custom_pages(status, updated_at desc);

create table if not exists public.site_menu_items (
  id bigint generated by default as identity primary key,
  system_key text unique,
  label_ru text not null,
  label_ro text not null default '',
  href text not null,
  visible boolean not null default true,
  display_order integer not null default 100,
  parent_id bigint references public.site_menu_items(id) on delete set null,
  custom_page_id bigint references public.site_custom_pages(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (parent_id is null or parent_id <> id)
);

create index if not exists site_menu_items_order_idx on public.site_menu_items(display_order, id);
create index if not exists site_menu_items_parent_idx on public.site_menu_items(parent_id, display_order, id);

alter table public.site_custom_pages enable row level security;
alter table public.site_menu_items enable row level security;

revoke all on table public.site_custom_pages from anon, authenticated;
revoke all on table public.site_menu_items from anon, authenticated;
grant select on table public.site_custom_pages to anon, authenticated;
grant select on table public.site_menu_items to anon, authenticated;
grant insert, update, delete on table public.site_custom_pages to authenticated;
grant insert, update, delete on table public.site_menu_items to authenticated;

drop policy if exists "Public reads published custom pages" on public.site_custom_pages;
create policy "Public reads published custom pages"
on public.site_custom_pages for select to anon, authenticated
using (status = 'published' or public.is_editor_or_admin());

drop policy if exists "Editors create custom pages" on public.site_custom_pages;
create policy "Editors create custom pages"
on public.site_custom_pages for insert to authenticated
with check (public.is_editor_or_admin());

drop policy if exists "Editors update custom pages" on public.site_custom_pages;
create policy "Editors update custom pages"
on public.site_custom_pages for update to authenticated
using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop policy if exists "Editors delete custom pages" on public.site_custom_pages;
create policy "Editors delete custom pages"
on public.site_custom_pages for delete to authenticated
using (public.is_editor_or_admin());

drop policy if exists "Public reads visible site menu" on public.site_menu_items;
create policy "Public reads visible site menu"
on public.site_menu_items for select to anon, authenticated
using (visible = true or public.is_editor_or_admin());

drop policy if exists "Editors create site menu" on public.site_menu_items;
create policy "Editors create site menu"
on public.site_menu_items for insert to authenticated
with check (public.is_editor_or_admin());

drop policy if exists "Editors update site menu" on public.site_menu_items;
create policy "Editors update site menu"
on public.site_menu_items for update to authenticated
using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop policy if exists "Editors delete site menu" on public.site_menu_items;
create policy "Editors delete site menu"
on public.site_menu_items for delete to authenticated
using (public.is_editor_or_admin());

