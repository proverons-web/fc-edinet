-- The side is the source of truth. team_id always follows the current match teams.
create or replace function public.sync_match_lineup_context()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_home_team_id bigint;
  v_away_team_id bigint;
begin
  select home_team_id, away_team_id
  into v_home_team_id, v_away_team_id
  from public.matches
  where id = new.match_id;

  if v_home_team_id is null or v_away_team_id is null then
    raise exception 'Match % does not exist', new.match_id;
  end if;

  if new.side = 'home' then
    new.team_id := v_home_team_id;
  else
    new.team_id := v_away_team_id;
  end if;

  return new;
end;
$$;

drop trigger if exists match_lineup_settings_sync_context on public.match_lineup_settings;
create trigger match_lineup_settings_sync_context
before insert or update of match_id, side, team_id on public.match_lineup_settings
for each row execute function public.sync_match_lineup_context();

drop trigger if exists match_lineup_entries_sync_context on public.match_lineup_entries;
create trigger match_lineup_entries_sync_context
before insert or update of match_id, side, team_id on public.match_lineup_entries
for each row execute function public.sync_match_lineup_context();

