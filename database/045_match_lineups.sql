create table if not exists public.match_lineup_settings (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  team_id bigint not null references public.teams(id) on delete cascade,
  side text not null check (side in ('home','away')),
  formation text,
  coach_name text,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_lineup_settings_match_side_unique unique (match_id, side)
);

create table if not exists public.match_lineup_entries (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  team_id bigint not null references public.teams(id) on delete cascade,
  side text not null check (side in ('home','away')),
  lineup_role text not null check (lineup_role in ('starter','substitute')),
  slot_number smallint not null check (slot_number between 1 and 30),
  player_id uuid references public.players(id) on delete set null,
  player_name text,
  shirt_number smallint check (shirt_number is null or shirt_number between 0 and 99),
  position text check (
    position is null or position in ('goalkeeper','defender','midfielder','forward')
  ),
  is_captain boolean not null default false,
  sort_order integer not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint match_lineup_entries_slot_unique unique (match_id, side, lineup_role, slot_number),
  constraint match_lineup_entries_player_or_name_check check (
    player_id is not null or nullif(btrim(player_name), '') is not null
  )
);

create index if not exists match_lineup_entries_match_side_idx
  on public.match_lineup_entries (match_id, side, lineup_role, slot_number);
create index if not exists match_lineup_entries_player_idx
  on public.match_lineup_entries (player_id, match_id);

