-- FC Edineț v2.30.19: non-destructive knockout bracket for cup competitions.
-- Run AFTER 081_cup_results.sql. This DOES NOT change matches, goals or existing seasons.
BEGIN;
CREATE TABLE IF NOT EXISTS public.cup_bracket_ties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competition_id bigint NOT NULL REFERENCES public.competitions(id) ON DELETE CASCADE,
  stage_order smallint NOT NULL CHECK (stage_order BETWEEN 1 AND 32),
  stage_name_ru text NOT NULL CHECK (char_length(trim(stage_name_ru)) BETWEEN 2 AND 100),
  stage_name_ro text CHECK (stage_name_ro IS NULL OR char_length(trim(stage_name_ro)) BETWEEN 2 AND 100),
  sort_order smallint NOT NULL CHECK (sort_order BETWEEN 1 AND 128),
  match_id bigint CONSTRAINT cup_bracket_ties_match_id_fkey REFERENCES public.matches(id) ON DELETE SET NULL,
  home_team_id bigint CONSTRAINT cup_bracket_ties_home_team_id_fkey REFERENCES public.teams(id) ON DELETE SET NULL,
  away_team_id bigint CONSTRAINT cup_bracket_ties_away_team_id_fkey REFERENCES public.teams(id) ON DELETE SET NULL,
  next_tie_id bigint CONSTRAINT cup_bracket_ties_next_tie_id_fkey REFERENCES public.cup_bracket_ties(id) ON DELETE RESTRICT,
  next_slot text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cup_bracket_ties_stage_position_key UNIQUE (competition_id,stage_order,sort_order),
  CONSTRAINT cup_bracket_ties_match_key UNIQUE (match_id),
  CONSTRAINT cup_bracket_ties_next_slot_key UNIQUE (next_tie_id,next_slot),
  CONSTRAINT cup_bracket_ties_slot_check CHECK (
    (next_tie_id IS NULL AND next_slot IS NULL) OR
    (next_tie_id IS NOT NULL AND next_slot IN ('home','away'))
  ),
  CONSTRAINT cup_bracket_ties_different_teams CHECK (home_team_id IS NULL OR away_team_id IS NULL OR home_team_id <> away_team_id),
  CONSTRAINT cup_bracket_ties_no_self_link CHECK (next_tie_id IS NULL OR next_tie_id <> id)
);
CREATE INDEX IF NOT EXISTS cup_bracket_ties_order_idx
  ON public.cup_bracket_ties(competition_id,stage_order,sort_order);
CREATE INDEX IF NOT EXISTS cup_bracket_ties_target_idx
  ON public.cup_bracket_ties(next_tie_id);

-- A tie may only reference a CUP edition; its match must belong to exactly that edition.
-- Forward links must point to a LATER round in the SAME cup. Reverse edits are also guarded.
CREATE SCHEMA IF NOT EXISTS private;
CREATE OR REPLACE FUNCTION private.validate_cup_bracket_tie()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, private AS $$
DECLARE linked record;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.competitions c
    WHERE c.id = NEW.competition_id AND c.competition_type = 'cup') THEN
    RAISE EXCEPTION 'Bracket tie requires a cup competition';
  END IF;
  IF NEW.match_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.matches m
    WHERE m.id = NEW.match_id AND m.competition_id = NEW.competition_id) THEN
    RAISE EXCEPTION 'Linked match must belong to this cup edition';
  END IF;
  IF NEW.next_tie_id IS NOT NULL THEN
    SELECT competition_id,stage_order INTO linked
      FROM public.cup_bracket_ties WHERE id = NEW.next_tie_id;
    IF NOT FOUND OR linked.competition_id <> NEW.competition_id
       OR linked.stage_order <= NEW.stage_order THEN
      RAISE EXCEPTION 'Next tie must belong to the same cup and a later round';
    END IF;
  END IF;
  IF NEW.id IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.cup_bracket_ties prior
    WHERE prior.next_tie_id = NEW.id AND
      (prior.competition_id <> NEW.competition_id OR prior.stage_order >= NEW.stage_order)
  ) THEN RAISE EXCEPTION 'Existing inbound links must point to a later round'; END IF;
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.validate_cup_bracket_tie() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS validate_cup_bracket_tie ON public.cup_bracket_ties;
CREATE TRIGGER validate_cup_bracket_tie BEFORE INSERT OR UPDATE ON public.cup_bracket_ties
FOR EACH ROW EXECUTE FUNCTION private.validate_cup_bracket_tie();


-- Moving a linked match to a different competition would orphan its cup placement.
CREATE OR REPLACE FUNCTION private.guard_match_bracket_competition()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, private AS $$
BEGIN
  IF OLD.competition_id IS DISTINCT FROM NEW.competition_id
     AND EXISTS (SELECT 1 FROM public.cup_bracket_ties WHERE match_id=NEW.id) THEN
    RAISE EXCEPTION 'Remove match from cup bracket before changing its competition';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.guard_match_bracket_competition() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS guard_match_bracket_competition ON public.matches;
CREATE TRIGGER guard_match_bracket_competition
BEFORE UPDATE OF competition_id ON public.matches
FOR EACH ROW EXECUTE FUNCTION private.guard_match_bracket_competition();

-- A competition cannot cease being a cup while it still has bracket ties.
CREATE OR REPLACE FUNCTION private.guard_competition_bracket_type()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER
SET search_path = pg_catalog, public, private AS $$
BEGIN
  IF NEW.competition_type IS DISTINCT FROM 'cup'
     AND EXISTS (SELECT 1 FROM public.cup_bracket_ties WHERE competition_id=NEW.id) THEN
    RAISE EXCEPTION 'Remove cup bracket before changing competition type';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.guard_competition_bracket_type() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS guard_competition_bracket_type ON public.competitions;
CREATE TRIGGER guard_competition_bracket_type
BEFORE UPDATE OF competition_type ON public.competitions
FOR EACH ROW EXECUTE FUNCTION private.guard_competition_bracket_type();

ALTER TABLE public.cup_bracket_ties ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public read active cup brackets" ON public.cup_bracket_ties;
CREATE POLICY "Public read active cup brackets" ON public.cup_bracket_ties
FOR SELECT TO anon, authenticated USING (
  EXISTS (SELECT 1 FROM public.competitions c WHERE c.id = competition_id
          AND c.is_active = true AND c.competition_type = 'cup')
);
DROP POLICY IF EXISTS "Editors read every cup bracket" ON public.cup_bracket_ties;
CREATE POLICY "Editors read every cup bracket" ON public.cup_bracket_ties
FOR SELECT TO authenticated USING ((SELECT public.is_editor_or_admin()));
DROP POLICY IF EXISTS "Editors insert cup brackets" ON public.cup_bracket_ties;
CREATE POLICY "Editors insert cup brackets" ON public.cup_bracket_ties
FOR INSERT TO authenticated WITH CHECK ((SELECT public.is_editor_or_admin()));
DROP POLICY IF EXISTS "Editors update cup brackets" ON public.cup_bracket_ties;
CREATE POLICY "Editors update cup brackets" ON public.cup_bracket_ties
FOR UPDATE TO authenticated USING ((SELECT public.is_editor_or_admin()))
WITH CHECK ((SELECT public.is_editor_or_admin()));
DROP POLICY IF EXISTS "Editors delete cup brackets" ON public.cup_bracket_ties;
CREATE POLICY "Editors delete cup brackets" ON public.cup_bracket_ties
FOR DELETE TO authenticated USING ((SELECT public.is_editor_or_admin()));
REVOKE ALL ON TABLE public.cup_bracket_ties FROM PUBLIC;
GRANT SELECT ON public.cup_bracket_ties TO anon;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.cup_bracket_ties TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.cup_bracket_ties_id_seq TO authenticated;
COMMENT ON TABLE public.cup_bracket_ties IS
 'Knockout progression layout. Winners are read from actual match results; bracket never mutates match teams or protocols.';
COMMIT;
