-- Site-wide Visual Editor for public section heroes and dynamic page templates.
-- Run AFTER 023_visual_page_editor.sql.

create table if not exists public.site_page_designs (
  page_key text primary key check (page_key in (
    'news','team','matches','standings','club','media','partners',
    'template_news','template_player','template_album'
  )),
  slug text generated always as (page_key) stored,
  background_mode text not null default 'default' check (background_mode in ('default','custom','content')),
  desktop_image_url text,
  mobile_image_url text,
  desktop_position_x integer not null default 50 check (desktop_position_x between 0 and 100),
  desktop_position_y integer not null default 50 check (desktop_position_y between 0 and 100),
  desktop_zoom_percent integer not null default 100 check (desktop_zoom_percent between 100 and 240),
  mobile_position_x integer not null default 50 check (mobile_position_x between 0 and 100),
  mobile_position_y integer not null default 50 check (mobile_position_y between 0 and 100),
  mobile_zoom_percent integer not null default 100 check (mobile_zoom_percent between 100 and 300),
  hero_height_desktop integer not null default 310 check (hero_height_desktop between 200 and 950),
  hero_height_mobile integer not null default 250 check (hero_height_mobile between 180 and 900),
  overlay_opacity integer not null default 58 check (overlay_opacity between 0 and 95),
  overlay_style text not null default 'solid' check (overlay_style in ('solid','gradient-left','gradient-right')),
  text_alignment text not null default 'left' check (text_alignment in ('left','center','right')),
  content_width integer not null default 720 check (content_width between 420 and 1200),
  show_eyebrow boolean not null default true,
  show_description boolean not null default true,
  eyebrow_ru text,
  eyebrow_ro text,
  title_ru text,
  title_ro text,
  description_ru text,
  description_ro text,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.site_page_design_drafts (
  page_key text primary key check (page_key in (
    'news','team','matches','standings','club','media','partners',
    'template_news','template_player','template_album'
  )),
  background_mode text not null default 'default' check (background_mode in ('default','custom','content')),
  desktop_image_url text,
  mobile_image_url text,
  desktop_position_x integer not null default 50 check (desktop_position_x between 0 and 100),
  desktop_position_y integer not null default 50 check (desktop_position_y between 0 and 100),
  desktop_zoom_percent integer not null default 100 check (desktop_zoom_percent between 100 and 240),
  mobile_position_x integer not null default 50 check (mobile_position_x between 0 and 100),
  mobile_position_y integer not null default 50 check (mobile_position_y between 0 and 100),
  mobile_zoom_percent integer not null default 100 check (mobile_zoom_percent between 100 and 300),
  hero_height_desktop integer not null default 310 check (hero_height_desktop between 200 and 950),
  hero_height_mobile integer not null default 250 check (hero_height_mobile between 180 and 900),
  overlay_opacity integer not null default 58 check (overlay_opacity between 0 and 95),
  overlay_style text not null default 'solid' check (overlay_style in ('solid','gradient-left','gradient-right')),
  text_alignment text not null default 'left' check (text_alignment in ('left','center','right')),
  content_width integer not null default 720 check (content_width between 420 and 1200),
  show_eyebrow boolean not null default true,
  show_description boolean not null default true,
  eyebrow_ru text,
  eyebrow_ro text,
  title_ru text,
  title_ro text,
  description_ru text,
  description_ro text,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.site_page_design_versions (
  id bigint generated by default as identity primary key,
  page_key text not null check (page_key in (
    'news','team','matches','standings','club','media','partners',
    'template_news','template_player','template_album'
  )),
  label text,
  snapshot jsonb not null,
  published_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

