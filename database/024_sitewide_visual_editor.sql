create index if not exists site_page_designs_updated_by_idx
  on public.site_page_designs (updated_by);
create index if not exists site_page_design_drafts_updated_by_idx
  on public.site_page_design_drafts (updated_by);
create index if not exists site_page_design_versions_page_created_idx
  on public.site_page_design_versions (page_key, created_at desc);
create index if not exists site_page_design_versions_published_by_idx
  on public.site_page_design_versions (published_by, created_at desc);

alter table public.site_page_designs enable row level security;
alter table public.site_page_design_drafts enable row level security;
alter table public.site_page_design_versions enable row level security;

grant select on table public.site_page_designs to anon, authenticated;
grant insert, update, delete on table public.site_page_designs to authenticated;
grant select, insert, update, delete on table public.site_page_design_drafts to authenticated;
grant select, insert on table public.site_page_design_versions to authenticated;
grant usage, select on sequence public.site_page_design_versions_id_seq to authenticated;

drop policy if exists "Public read site page designs" on public.site_page_designs;
create policy "Public read site page designs"
on public.site_page_designs for select to anon, authenticated using (true);

drop policy if exists "Editors insert site page designs" on public.site_page_designs;
create policy "Editors insert site page designs"
on public.site_page_designs for insert to authenticated with check (public.is_editor_or_admin());

drop policy if exists "Editors update site page designs" on public.site_page_designs;
create policy "Editors update site page designs"
on public.site_page_designs for update to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop policy if exists "Editors delete site page designs" on public.site_page_designs;
create policy "Editors delete site page designs"
on public.site_page_designs for delete to authenticated using (public.is_editor_or_admin());

drop policy if exists "Editors manage site page design drafts" on public.site_page_design_drafts;
create policy "Editors manage site page design drafts"
on public.site_page_design_drafts for all to authenticated
using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop policy if exists "Editors read site page design versions" on public.site_page_design_versions;
create policy "Editors read site page design versions"
on public.site_page_design_versions for select to authenticated
using (public.is_editor_or_admin());

drop policy if exists "Editors create site page design versions" on public.site_page_design_versions;
create policy "Editors create site page design versions"
on public.site_page_design_versions for insert to authenticated
with check (public.is_editor_or_admin());

-- Published design changes are part of the existing audit log.
drop trigger if exists audit_log_site_page_designs on public.site_page_designs;
create trigger audit_log_site_page_designs
after insert or update or delete on public.site_page_designs
for each row execute function public.write_audit_log();
