create table if not exists public.club_archive_albums (
  id bigint generated by default as identity primary key,
  title text not null,
  title_ro text,
  period_label text,
  period_label_ro text,
  description text,
  description_ro text,
  cover_url text,
  display_order integer not null default 100,
  is_active boolean not null default true,
  is_placeholder boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists club_archive_albums_active_order_idx on public.club_archive_albums(is_active,display_order,id);
drop trigger if exists club_archive_albums_set_updated_at on public.club_archive_albums;
create trigger club_archive_albums_set_updated_at before update on public.club_archive_albums for each row execute function public.set_generic_updated_at();

create table if not exists public.club_archive_photos (
  id bigint generated by default as identity primary key,
  album_id bigint not null references public.club_archive_albums(id) on delete cascade,
  image_url text not null,
  caption text,
  caption_ro text,
  year_label text,
  source_credit text,
  display_order integer not null default 100,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists club_archive_photos_album_order_idx on public.club_archive_photos(album_id,is_active,display_order,id);
drop trigger if exists club_archive_photos_set_updated_at on public.club_archive_photos;
create trigger club_archive_photos_set_updated_at before update on public.club_archive_photos for each row execute function public.set_generic_updated_at();

create table if not exists public.club_hall_of_fame (
  id bigint generated by default as identity primary key,
  entry_type text not null default 'person' check (entry_type in ('person','squad')),
  category text not null default 'player' check (category in ('player','coach','leader','squad')),
  first_name text,
  last_name text,
  title text not null,
  title_ro text,
  era_label text,
  era_label_ro text,
  description text,
  description_ro text,
  roster_text text,
  roster_text_ro text,
  photo_url text,
  display_order integer not null default 100,
  is_active boolean not null default true,
  is_placeholder boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists club_hall_of_fame_active_order_idx on public.club_hall_of_fame(is_active,category,display_order,id);
drop trigger if exists club_hall_of_fame_set_updated_at on public.club_hall_of_fame;
create trigger club_hall_of_fame_set_updated_at before update on public.club_hall_of_fame for each row execute function public.set_generic_updated_at();

alter table public.club_archive_albums enable row level security;
alter table public.club_archive_photos enable row level security;
alter table public.club_hall_of_fame enable row level security;

grant select on table public.club_archive_albums, public.club_archive_photos, public.club_hall_of_fame to anon, authenticated;
grant insert, update, delete on table public.club_archive_albums, public.club_archive_photos, public.club_hall_of_fame to authenticated;
grant usage, select on sequence public.club_archive_albums_id_seq, public.club_archive_photos_id_seq, public.club_hall_of_fame_id_seq to authenticated;

drop policy if exists "Public can read active archive albums" on public.club_archive_albums;
create policy "Public can read active archive albums" on public.club_archive_albums for select to public using (is_active=true);
drop policy if exists "Editors read all archive albums" on public.club_archive_albums;
create policy "Editors read all archive albums" on public.club_archive_albums for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors manage archive albums" on public.club_archive_albums;
create policy "Editors manage archive albums" on public.club_archive_albums for all to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop policy if exists "Public can read active archive photos" on public.club_archive_photos;
create policy "Public can read active archive photos" on public.club_archive_photos for select to public using (is_active=true and exists(select 1 from public.club_archive_albums a where a.id=album_id and a.is_active=true));
drop policy if exists "Editors read all archive photos" on public.club_archive_photos;
create policy "Editors read all archive photos" on public.club_archive_photos for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors manage archive photos" on public.club_archive_photos;
create policy "Editors manage archive photos" on public.club_archive_photos for all to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop policy if exists "Public can read active hall of fame" on public.club_hall_of_fame;
create policy "Public can read active hall of fame" on public.club_hall_of_fame for select to public using (is_active=true);
drop policy if exists "Editors read all hall of fame" on public.club_hall_of_fame;
create policy "Editors read all hall of fame" on public.club_hall_of_fame for select to authenticated using (public.is_editor_or_admin());
drop policy if exists "Editors manage hall of fame" on public.club_hall_of_fame;
create policy "Editors manage hall of fame" on public.club_hall_of_fame for all to authenticated using (public.is_editor_or_admin()) with check (public.is_editor_or_admin());

drop trigger if exists audit_log_club_archive_albums on public.club_archive_albums;
