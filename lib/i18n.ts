export type Locale = "ru" | "ro";

export const DEFAULT_LOCALE: Locale = "ru";
export const LOCALE_COOKIE = "fc_locale";

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "ru" || value === "ro";
}

export function localized(
  primary: string | null | undefined,
  romanian: string | null | undefined,
  locale: Locale
) {
  if (locale === "ro" && romanian?.trim()) return romanian.trim();
  return primary?.trim() || "";
}

export function dateLocale(locale: Locale) {
  return locale === "ro" ? "ro-RO" : "ru-RU";
}

